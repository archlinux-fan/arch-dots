-- mod-version:3
-- persistent_syntax: pick a syntax for a file and remember it across sessions.
-- Choices live in USERDIR/syntax_choices.lua (absolute path -> syntax name).
-- Replaces force_syntax; do not load both.

local core = require "core"
local common = require "core.common"
local command = require "core.command"
local syntax = require "core.syntax"
local style = require "core.style"
local Doc = require "core.doc"
local DocView = require "core.docview"
local StatusView = require "core.statusview"

local AUTO, CURRENT = "Auto detect", "Current: "
local plain_text = syntax.plain_text_syntax or syntax.get("", "")
plain_text.name = plain_text.name or "Plain Text"


local function syntax_name(s)
  if not s then return "Undefined" end
  if s.name then return s.name end
  local files = type(s.files) == "string" and { s.files } or s.files or {}
  return #files > 0 and table.concat(files, ", ") or "Undefined"
end

local function find_syntax(name)
  if name == plain_text.name then return plain_text end
  for _, s in ipairs(syntax.items) do
    if syntax_name(s) == name then return s end
  end
end


local Store = { path = USERDIR .. PATHSEP .. "syntax_choices.lua", map = {} }

function Store:load()
  local f = io.open(self.path, "r")
  if not f then return end
  -- Empty environment: the file can only return data, never call anything.
  local chunk = load(f:read("*a"), "=" .. self.path, "t", {})
  f:close()
  local ok, t = pcall(chunk)
  if not (ok and type(t) == "table") then
    return core.error("persistent_syntax: cannot parse %s", self.path)
  end
  for k, v in pairs(t) do
    if type(k) == "string" and type(v) == "string" then self.map[k] = v end
  end
end

function Store:save()
  local keys = {}
  for k in pairs(self.map) do keys[#keys + 1] = k end
  table.sort(keys)
  local lines = { "-- generated by persistent_syntax: file path -> syntax name", "return {" }
  for _, k in ipairs(keys) do
    lines[#lines + 1] = string.format("  [%q] = %q,", k, self.map[k])
  end
  lines[#lines + 1] = "}\n"

  -- Write to a temp file and rename, so a failed write never truncates the store.
  local tmp = self.path .. ".tmp"
  local f, err = io.open(tmp, "w")
  local ok = f and f:write(table.concat(lines, "\n")) and f:close()
  if ok then ok, err = os.rename(tmp, self.path) end
  if not ok then
    os.remove(tmp)
    core.error("persistent_syntax: cannot write %s: %s", self.path, err or "write failed")
  end
  return ok
end

function Store:get(path)
  local name = path and self.map[path]
  return name and find_syntax(name)
end

function Store:set(path, name)
  if not path or self.map[path] == name then return end
  self.map[path] = name
  if self:save() then
    core.log("%s syntax for %s in %s", name and ('Saved "' .. name .. '"') or "Removed",
             path, self.path)
  end
end

Store:load()


-- The chosen syntax sticks to the doc, so it survives "Save As" and is stored
-- as soon as an unsaved doc gets a path.
local reset_syntax = Doc.reset_syntax
function Doc:reset_syntax()
  self.forced_syntax = self.forced_syntax or Store:get(self.abs_filename)
  local forced = self.forced_syntax
  if not forced then return reset_syntax(self) end
  Store:set(self.abs_filename, syntax_name(forced))
  if self.syntax ~= forced then
    self.syntax = forced
    self.highlighter:soft_reset()
  end
end


local function active_doc()
  local view = core.active_view
  if not (view and view:is(DocView)) then view = core.last_active_view end
  if view and view:is(DocView) then return true, view.doc end
end

-- Returns label -> syntax (false = auto detect) and the labels in display order:
-- current syntax, "Auto detect", then everything else alphabetically.
local function syntax_choices(doc)
  local map, names, seen, current = { [AUTO] = false }, {}, {}, nil
  local function add(s)
    local base = syntax_name(s)
    local name, i = base, 1
    while seen[name] do i = i + 1; name = base .. " (" .. i .. ")" end
    seen[name] = true
    if s == doc.syntax then
      current = CURRENT .. name
      map[current] = s
    else
      map[name] = s
      names[#names + 1] = name
    end
  end
  add(plain_text)
  for _, s in ipairs(syntax.items) do add(s) end

  table.sort(names, function(a, b) return a:lower() < b:lower() end)
  table.insert(names, 1, AUTO)
  if current then table.insert(names, 1, current) end
  return map, names
end


core.status_view:add_item({
  predicate = active_doc,
  name = "doc:persistent-syntax",
  alignment = StatusView.Item.RIGHT,
  get_item = function()
    local _, doc = active_doc()
    return { style.text, syntax_name(doc.syntax) }
  end,
  command = "persistent-syntax:select-file-syntax",
  position = -1,
  tooltip = "file syntax",
  separator = core.status_view.separator2
})

command.add(active_doc, {
  ["persistent-syntax:select-file-syntax"] = function(doc)
    local map, names = syntax_choices(doc)
    core.command_view:enter("Set syntax for this file", {
      submit = function(_, item)
        local s = item and map[item.text]
        if s == nil then return end
        doc.forced_syntax = s or nil
        if not s then Store:set(doc.abs_filename, nil) end
        doc:reset_syntax()
      end,
      suggest = function(text)
        return text == "" and names or common.fuzzy_match(names, text)
      end
    })
  end
})

command.add(nil, {
  ["persistent-syntax:open-store"] = function()
    core.root_view:open_doc(core.open_doc(Store.path))
  end
})
